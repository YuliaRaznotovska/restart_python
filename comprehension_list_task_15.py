# 🔹 Task 15. Перетворення чисел на “even/odd” і подвоєння парних
# Є список чисел:
# numbers = [1, 2, 3, 4, 5, 6]
# Створи новий список, де:
# парні числа подвоєні і записані як числа
# непарні числа записані як рядок “odd”
numbers = [1, 2, 3, 4, 5, 6]
new_list = [num * 2 if num % 2 == 0 else 'odd' for num in numbers]
print(new_list)
